cat("\n########## 5. 非劣效(均数) rct/noninferiority/mean ##########\n")
# mean1=10(试验), mean2=9.5(对照), margin=1 -> delta_e = 10-9.5+1 = 1.5
ours <- calculate("rct", "noninferiority", "mean", mean1 = 10, mean2 = 9.5, sd = 3, margin = 1)
cat("sampleSizeCalc n/组 =", ours$n_per_group, "\n")
# 注意：我们的 margin 与 mean2-margin 传统参数化不同
# 传统: delta_e = margin - (mu1-mu2) = 1 - 0.5 = 0.5 (Chow 口径)
ts_r <- TrialSize::TwoSampleMean.NIS(alpha = 0.05, beta = 0.2, sigma = 3, k = 1, delta = 0.5, margin = 1)
cat("TrialSize::TwoSampleMean.NIS(Chow口径 delta=0.5) n =", ceiling(ts_r), "\n")
z_a <- qnorm(0.95); z_b <- qnorm(0.8)
n_manual <- ceiling(2 * (z_a + z_b)^2 * 9 / 1.5^2)
cat("手工公式(我们的 delta_e=1.5) n =", n_manual, "\n")

